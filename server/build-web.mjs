// Bundles the browser decrypt page into a TS module the Worker imports.
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, 'src', 'web');

const result = await build({
  entryPoints: [join(web, 'client.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});

const assets = {
  html: readFileSync(join(web, 'page.html'), 'utf8'),
  landing: readFileSync(join(web, 'landing.html'), 'utf8'),
  logo: readFileSync(join(web, 'logo.svg'), 'utf8'),
  css: readFileSync(join(web, 'style.css'), 'utf8'),
  js: result.outputFiles[0].text,
};

mkdirSync(join(web, 'generated'), { recursive: true });
writeFileSync(
  join(web, 'generated', 'assets.ts'),
  `// GENERATED by build-web.mjs. Do not edit.\nimport type { WebAssets } from '../../app';\nexport const webAssets: WebAssets = ${JSON.stringify(assets)};\n`,
);
console.log(`web assets built (client.js ${assets.js.length} bytes)`);
